-- 2. TABEL: EDUCATIONS (Riwayat Pendidikan)
CREATE TABLE IF NOT EXISTS public.educations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution TEXT NOT NULL,
    degree TEXT NOT NULL,
    field_of_study TEXT NOT NULL,
    start_date TEXT NOT NULL,
    end_date TEXT NOT NULL,
    is_current BOOLEAN DEFAULT FALSE,
    description TEXT,
    achievements JSONB DEFAULT '[]'::JSONB,
    logo_icon TEXT DEFAULT 'GraduationCap',
    sort_order INT DEFAULT 1,
    is_visible BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABEL: EXPERIENCES (Pengalaman Kerja & Organisasi)
CREATE TABLE IF NOT EXISTS public.experiences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization TEXT NOT NULL,
    position TEXT NOT NULL,
    experience_type TEXT DEFAULT 'Kerja',
    start_date TEXT NOT NULL,
    end_date TEXT NOT NULL,
    is_current BOOLEAN DEFAULT FALSE,
    description TEXT,
    achievements JSONB DEFAULT '[]'::JSONB,
    technologies JSONB DEFAULT '[]'::JSONB,
    sort_order INT DEFAULT 1,
    is_visible BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. TABEL: SKILL_CATEGORIES (Kategori Keahlian & Daftar Skill)
CREATE TABLE IF NOT EXISTS public.skill_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    sort_order INT DEFAULT 1,
    is_visible BOOLEAN DEFAULT TRUE,
    skills JSONB DEFAULT '[]'::JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. TABEL: PROJECTS (Proyek Portofolio & Galeri Dokumentasi)
CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    slug TEXT NOT NULL,
    project_category TEXT DEFAULT 'Full-Stack Web',
    summary TEXT,
    description TEXT,
    cover_image TEXT,
    images JSONB DEFAULT '[]'::JSONB,
    technologies JSONB DEFAULT '[]'::JSONB,
    live_url TEXT,
    repository_url TEXT,
    demo_status TEXT DEFAULT 'PUBLIC',
    publication_status TEXT DEFAULT 'PUBLISHED',
    sort_order INT DEFAULT 1,
    featured BOOLEAN DEFAULT FALSE,
    published_at TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. TABEL: SITE_SETTINGS (Pengaturan Website Publik)
CREATE TABLE IF NOT EXISTS public.site_settings (
    id BIGINT PRIMARY KEY DEFAULT 1,
    site_title TEXT DEFAULT 'Alifian Ramadhan — Web Developer & UI Designer',
    tagline TEXT DEFAULT 'Portofolio Profesional & Sistem Dokumentasi Proyek',
    meta_description TEXT DEFAULT 'Portofolio profesional Alifian Ramadhan, mahasiswa Manajemen Informatika dan Web Developer.',
    favicon_url TEXT DEFAULT '',
    contact_email TEXT DEFAULT 'alifian.work@example.com',
    is_maintenance_mode BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. TABEL: SOCIAL_LINKS (Tautan Media Sosial)
CREATE TABLE IF NOT EXISTS public.social_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform TEXT NOT NULL,
    url TEXT NOT NULL,
    icon_name TEXT DEFAULT 'Globe',
    sort_order INT DEFAULT 1,
    is_visible BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. TABEL: CONTACT_MESSAGES (Kotak Masuk Pesan Pengunjung)
CREATE TABLE IF NOT EXISTS public.contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_name TEXT NOT NULL,
    sender_email TEXT NOT NULL,
    subject TEXT DEFAULT '(Tanpa Subjek)',
    message TEXT NOT NULL,
    status TEXT DEFAULT 'NEW',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. TABEL: THEME_SETTINGS (Preferensi Warna & Tema Web)
CREATE TABLE IF NOT EXISTS public.theme_settings (
    id BIGINT PRIMARY KEY DEFAULT 1,
    primary_color TEXT DEFAULT '#17634D',
    primary_hover TEXT DEFAULT '#124F3E',
    primary_pale TEXT DEFAULT '#E8F1EC',
    primary_light TEXT DEFAULT '#F0F6F2',
    primary_border TEXT DEFAULT '#C8DCD1',
    bg_main TEXT DEFAULT '#F7F7F3',
    preset_name TEXT DEFAULT 'Forest Green (Default PRD)',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

